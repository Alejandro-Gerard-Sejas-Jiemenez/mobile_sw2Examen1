import { Dimensions } from 'react-native';
import { Easing, Keyframe } from 'react-native-reanimated';
import { AnimationTokens } from '@/constants/theme';

const INITIAL_SCALE_FACTOR =
  Dimensions.get('screen').height / AnimationTokens.INITIAL_SCALE_DIVISOR;

/**
 * Native Splash Overlay keyframe
 */
export const splashKeyframe = new Keyframe({
  0: {
    transform: [{ scale: 1 }],
    opacity: 1,
  },
  20: {
    opacity: 1,
  },
  70: {
    opacity: 0,
    easing: Easing.elastic(0.7),
  },
  100: {
    opacity: 0,
    transform: [{ scale: 1 }],
    easing: Easing.elastic(0.7),
  },
});

/**
 * Native Icon Background scale keyframe
 */
export const iconScaleKeyframe = new Keyframe({
  0: {
    transform: [{ scale: INITIAL_SCALE_FACTOR }],
  },
  100: {
    transform: [{ scale: 1 }],
    easing: Easing.elastic(0.7),
  },
});

